"""Render complete bank mix variants once, preserve source gain/delay and tails."""
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path
from collections import Counter
import array
import hashlib
import json
import re
import subprocess
import sys
import wave
from prepare_gameplay_audio_scope import ROOT, OUT, EXTRACT, read

RECIPES=OUT/(sys.argv[1] if len(sys.argv)>1 else 'BankRecipes02')/'txtp'
DEST=EXTRACT/(sys.argv[2] if len(sys.argv)>2 else 'Decoded01')
DEST.mkdir(exist_ok=False)
VGM=Path('C:/Users/user/Downloads/63a7cbccd9fbaae9db45240069a49bd6a3a00b73/Output/.data/vgmstream-cli.exe')

def render(p):
    body=p.read_text(encoding='utf-8-sig')
    event_ids=re.findall(r'CAkEvent\[\d+\] (\d+)',body)
    if not event_ids:
        return {'recipe':str(p),'status':'no_event_id'}
    switches=re.findall(r'\[([^\]]+)\]',p.stem)
    if any(s.startswith(('vo_kz_switch=','kz_apc_switch=')) and not s.endswith('=kz') for s in switches):
        return {'recipe':str(p),'status':'excluded_other_character_switch','event_ids':event_ids}
    ident=hashlib.sha256(body.encode()).hexdigest()[:16]
    name='SW_'+event_ids[0]+'_'+ident
    target=DEST/(name+'.wav')
    args=[str(VGM),'-i','-o',str(target),str(p)]
    proc=subprocess.run(args,stdout=subprocess.PIPE,stderr=subprocess.STDOUT)
    row={'recipe':str(p),'recipe_name':p.stem,'recipe_sha256':hashlib.sha256(p.read_bytes()).hexdigest(),
         'event_ids':event_ids,'switches':switches,'wave_file':str(target),'wave_name':name,
         'loop': bool(re.search(r'(?:#e\b|#l\b|group\s*=.*-L)',body.split('# AUTOGENERATED')[0])),
         'status':'decoded' if proc.returncode==0 else 'decode_failed',
         'decoder_log':proc.stdout.decode('utf-8',errors='replace')}
    if proc.returncode==0:
        with wave.open(str(target),'rb') as stream:
            row.update(channels=stream.getnchannels(),sample_rate=stream.getframerate(),frames=stream.getnframes(),
                       sample_bytes=stream.getsampwidth(),seconds=stream.getnframes()/stream.getframerate())
            samples=array.array('h',stream.readframes(stream.getnframes()))
        row['peak']=max((abs(n) for n in samples),default=0)/32768
        row['clipped_samples']=sum(abs(n)>=32767 for n in samples)
        row['source_mix_gain_lines']=[l.strip() for l in body.splitlines() if '#v' in l and not l.startswith('#')]
        row['wave_sha256']=hashlib.sha256(target.read_bytes()).hexdigest()
    return row

rows=[]
with ThreadPoolExecutor(max_workers=4) as pool:
    pending=[pool.submit(render,p) for p in sorted(RECIPES.glob('*.txtp'))]
    for i,future in enumerate(as_completed(pending),1):
        rows.append(future.result())
        if i%100==0:
            print('DECODE',i,'/',len(pending),flush=True)
            (OUT/'DecodeProgress.json').write_text(json.dumps({'done':i,'total':len(pending),'counts':dict(Counter(r['status'] for r in rows))},indent=2),encoding='utf-8')
(OUT/(sys.argv[3] if len(sys.argv)>3 else 'DecodedManifest01.json')).write_text(json.dumps(sorted(rows,key=lambda r:r['recipe']),ensure_ascii=False,indent=2),encoding='utf-8')
print('DECODE FINISHED',Counter(r['status'] for r in rows),'clipping',sum(r.get('clipped_samples',0) for r in rows),flush=True)
