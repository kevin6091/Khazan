"""TXTP source hierarchy -> native cue plan. Keeps nested randoms, not snapshots."""
from collections import Counter
from pathlib import Path
import hashlib
import json
import re
import xml.etree.ElementTree as ET
from prepare_gameplay_audio_scope import ROOT, OUT, EXTRACT, read

FACTS=read(OUT/'BankNodeFacts.json')
MEDIA_OVERLAY={p.name:p for base in ('Raw03','Raw04','Raw05','Raw06','Raw07') for p in (EXTRACT/base/'BBQ/Content/WwiseAudio/Media').rglob('*.wem')}
SURFACES={Path(r['target']).stem.lower():int(re.search(r'\d+',read(r['target'])[0]['Properties']['SurfaceType'])[0])
          for r in read(EXTRACT/'Physical01/MetadataExtractionReport.json') if r['status']=='ok'}

def signature(n):
    if n['kind']=='wave':return Counter([Path(n['media']).stem])
    if n['kind']=='silence':return Counter()
    return sum((signature(c) for c in n['children']),Counter())

def path_tree(text):
    roots=[];stack=[]
    for line in text.split('# PATH',1)[1].split('# STATECHUNKS',1)[0].splitlines():
        m=re.match(r'#(\s+)(CAk\w+)\[\d+\] (\d+)',line)
        if m:
            depth=len(m[1]);node={'kind':m[2],'id':m[3],'children':[],'media':[]}
            while stack and stack[-1][0]>=depth:stack.pop()
            (stack[-1][1]['children'] if stack else roots).append(node)
            stack.append((depth,node))
        else:
            m=re.match(r'#\s+Source (\d+)',line)
            if m and stack:stack[-1][1]['media'].append(m[1])
    def visit(n):
        for c in n['children']:yield from visit(c)
        n['signature']=sum((c['signature'] for c in n['children']),Counter())+Counter(n['media'])
        yield n
    return [n for r in roots for n in visit(r)]

def modifiers(text):
    out={}
    for name, key in (('v','gain_db'),('p','pad_before'),('P','pad_after')):
        m=re.search(r'#'+name+r'\s+([-\d.]+)(dB)?',text)
        if m:out[key]=float(m[1])
    if re.search(r'#(?:B|r|b|m)\b',text):out['complex_commands']=text
    return out

def parse_recipe(p):
    text=p.read_text(encoding='utf-8-sig');stack=[];pathnodes=path_tree(text)
    for line in text.split('# AUTOGENERATED',1)[0].splitlines():
        line=line.strip()
        if not line or line.startswith('#'):continue
        if line.startswith('group'):
            m=re.search(r'-([RLS])(\d+)(?:>([\d-]+))?',line)
            if not m:raise ValueError(line)
            count=int(m[2]);children=stack[-count:];del stack[-count:]
            assert len(children)==count,(p.name,line,len(children))
            kind={'R':'random','L':'mixer','S':'sequence'}[m[1]]
            node={'kind':kind,'children':children,**modifiers(line)}
            if '#@loop' in line:node['loop']=True
            sig=signature(node)
            typ={'R':'CAkRanSeqCntr','L':'CAkLayerCntr','S':'CAkRanSeqCntr'}[m[1]]
            match=next((n for n in pathnodes if n['kind']==typ and n['signature']==sig),None)
            if match:
                node['source_node']=match['id'];fact=FACTS.get(match['id'],{})
                if kind=='sequence' and next((f['value'] for f in fact.get('fields',[]) if f['name']=='bIsContinuous'),'1')=='0':
                    # A Wwise step sequence chooses ONE item per posted event.
                    # Concatenating the whole pool would play minutes of voices.
                    # Native random bag preserves one-item duration/variants;
                    # its order is an explicit adapter to the source ordered pool.
                    node['kind']=kind='random'
                    node['adapter']='Wwise non-continuous sequence-step -> native one-item shuffle bag; original ordering not emulated.'
                if kind=='random':
                    playlist=fact.get('playlist',[])
                    weights=[]
                    for child in children:
                        childsig=signature(child)
                        childsrc=next((n for n in match['children'] if n['signature']==childsig),None)
                        row=next((r for r in playlist if childsrc and r['ulPlayID']==childsrc['id']),None)
                        weights.append(float(row['weight']) if row else 0.)
                    if not all(weights):
                        values={r['weight'] for r in playlist}
                        if len(values)==1:weights=[float(next(iter(values)))]*count
                        else:raise ValueError(('Unresolved nonuniform random weights',p.name,node['source_node']))
                    node['weights']=weights
                    # UE's without-replacement bag differs from Wwise Normal with
                    # avoid-repeat1. It avoids immediately repeated footsteps/voices.
                    avoid=next((f['value'] for f in fact['fields'] if f['name']=='wAvoidRepeatCount'),'0')
                    node['avoid_repeat']=int(avoid)
                if kind=='mixer' and fact.get('xml'):
                    xml=ET.fromstring(fact['xml'])
                    layer=next((e for e in xml.iter('object') if e.get('name')=='LayerInitialValues'),None)
                    if layer is not None:
                        curves=[]
                        used_children=set()
                        rtpc=next((f.get('value') for f in layer.findall('field') if f.get('name')=='rtpcID'),None)
                        for child in children:
                            childsrc=next((n for n in match['children'] if n['signature']==signature(child) and n['id'] not in used_children),None)
                            if childsrc:used_children.add(childsrc['id'])
                            assoc=next((e for e in xml.iter('object') if e.get('name')=='CAssociatedChildData' and
                                any(f.get('name')=='ulAssociatedChildID' and childsrc and f.get('value')==childsrc['id'] for f in e.findall('field'))),None)
                            curve=[{f.get('name'):float(f.get('value')) for f in e.findall('field')}
                                for e in assoc.iter('object') if e.get('name')=='AkRTPCGraphPoint'] if assoc is not None else []
                            curves.append(curve)
                        if all(curves):node['rtpc_layer']={'rtpc_id':rtpc,'curves':curves}
            stack.append(node)
        else:
            m=re.match(r'(.*?\.wem)(.*)',line)
            if m:
                node={'kind':'wave','media':m[1].strip(),'gain_db':0.,'loop':bool(re.search(r'#e\b',m[2])),**modifiers(m[2])}
                if not Path(node['media']).exists():
                    overlay=MEDIA_OVERLAY.get(Path(node['media']).name)
                    if overlay:node['media']=str(overlay).replace('\\','/')
                # Keep trimming/padding in the original decoder, gain stays a native float.
                extra=re.sub(r'#v\s+[-\d.]+dB','',m[2]).split('##')[0]
                extra=re.sub(r'#e\b','',extra).strip()
                node['decode_commands']=extra
                node.pop('complex_commands',None);node.pop('pad_before',None);node.pop('pad_after',None)
            elif line.startswith('?.plugin-silence'):
                m=re.search(r'#B\s+([\d.]+)',line)
                node={'kind':'silence','seconds':float(m[1]) if m else 0.}
            elif line.startswith('?.plugin-tone'):
                node={'kind':'silence','seconds':0.,'adapter':'Controller feedback/source tone branch omitted from audible mix; raw bank preserved.'}
            else:raise ValueError(('Unsupported source plugin',line))
            stack.append(node)
    assert stack,p.name
    node=stack[0] if len(stack)==1 else {'kind':'sequence','children':stack}
    return {'recipe':str(p),'recipe_sha256':hashlib.sha256(p.read_bytes()).hexdigest(),'graph':node,
            'switches':dict(s.split('=',1) for s in re.findall(r'\[([^\]]+)\]',p.stem) if '=' in s),
            'event_ids':re.findall(r'CAkEvent\[\d+\] (\d+)',text),'source_gamevars':text.split('# GAMEVARS',1)[-1] if '# GAMEVARS' in text else ''}

def walk(n):
    yield n
    for c in n.get('children',[]):yield from walk(c)
    if n['kind']=='surface_switch':
        for c in list(n['branches'].values())+[n['default']]:yield from walk(c)

def main():
    resource=read(OUT/'ResourcePlan.json');by_id={str(r['cooked']['EventId']):r for r in resource['events']}
    groups={};excluded=[];fallback=[]
    for p in sorted([p for folder in ('BankRecipes08','BankRecipes09','BankRecipes10','BankRecipes11','BankRecipes12') for p in (OUT/folder/'txtp').glob('*.txtp')]):
        text=p.read_text(encoding='utf-8-sig');ids=re.findall(r'CAkEvent\[\d+\] (\d+)',text)
        if not ids or ids[0] not in by_id:continue
        switches=re.findall(r'\[([^\]]+)\]',p.stem)
        if any(s.startswith(('vo_kz_switch=','kz_apc_switch=')) and not s.endswith('=kz') for s in switches):continue
        if by_id[ids[0]]['name']=='efx_apesstonehand_projectile_switch' and '3450111232=2144363834' not in switches:
            # Current Apes COI SoundData.SwitchState=Rock. Wwise's lowercase
            # FNV-1 rock hash is2144363834; don't randomly choose another state.
            excluded.append(dict(recipe=str(p),reason='Current Apes projectile source SwitchState=Rock; other source projectile states unused'));continue
        try:
            row=parse_recipe(p)
            if any('complex_commands' in n for n in walk(row['graph'])):
                fallback.append(dict(row,reason='Group trim/body commands require exact flattened variants'));continue
            # physical_material_above is optional extra wet/blood layer; requires
            # a second independent source switch and is not the ground base branch.
            if 'physical_material_above' in row['switches']:excluded.append(dict(recipe=str(p),reason='Optional above-surface layer has no current project producer'));continue
            ident=hashlib.sha256(json.dumps([row['switches'],row['graph']],sort_keys=True).encode()).hexdigest()
            groups.setdefault(ids[0],{})[ident]=row
        except Exception as e:fallback.append({'recipe':str(p),'event_ids':ids,'reason':str(e)})
    cues=[];waves={}
    for sid,variants in groups.items():
        event=by_id[sid];rows=list(variants.values())
        ground={};general=[]
        for r in rows:
            surface=r['switches'].get('physical_material')
            if surface:ground.setdefault(SURFACES.get(surface,0),[]).append(r['graph'])
            else:general.append(r['graph'])
        def choice(nodes):
            unique={json.dumps(n,sort_keys=True):n for n in nodes}
            return list(unique.values())[0] if len(unique)==1 else {'kind':'random','children':list(unique.values()),'weights':[1.]*len(unique),'avoid_repeat':1,'adapter':'Switch condition without a current producer uses source variants.'}
        if ground:
            branches={str(k):choice(v) for k,v in ground.items()}
            default=branches.get('3') or next(iter(branches.values()))
            node={'kind':'surface_switch','children':[],'branches':branches,'default':default}
            if general:node={'kind':'mixer','children':[node,choice(general)]}
        else:node=choice(general)
        name='SC_'+re.sub(r'[^A-Za-z0-9_]','_',event['name'])
        cue={'event_id':sid,'event_package':event['source_package'],'event_name':event['name'],
             'asset':'/Game/Audio/Original/Events/'+name,'graph':node,'recipes':[r['recipe'] for r in rows],
             'source':event,'loop':any(n.get('loop') for r in rows for n in walk(r['graph']))}
        cues.append(cue)
        nodes=list(walk(node))
        for n in nodes:
            if n['kind']=='wave':
                key=json.dumps([n['media'],n['decode_commands']],sort_keys=True)
                ident=hashlib.sha256(key.encode()).hexdigest()[:14]
                n['wave_key']=ident
                waves[ident]={'key':ident,'media':n['media'],'commands':n['decode_commands'],
                    'wave_file':str(EXTRACT/'NativeDecoded01'/('SW_'+Path(n['media']).stem+'_'+ident+'.wav')),
                    'asset':'/Game/Audio/Original/Media/SW_'+Path(n['media']).stem+'_'+ident,'needed_loop':n.get('loop',False) or waves.get(ident,{}).get('needed_loop',False)}
    plan={'cues':cues,'waves':list(waves.values()),'fallback':fallback,'excluded':excluded,'surface_types':SURFACES,
          'numeric_policy':{'gain':'10^(source_gain_db/20), cue/wave unity',
            'random':'Source bank playlist weights; UE without-replacement bag for source avoidRepeat>0',
            'layer':'All source layers, speed-conditional layer curve restored where exposed',
            'adapter':'Non-produced source switches/RTPCs and native DSP are documented adaptations.'}}
    (OUT/'NativeCuePlan01.json').write_text(json.dumps(plan,ensure_ascii=False,indent=2),encoding='utf-8')
    print('NATIVE',len(cues),'WAVES',len(waves),'FALLBACK RECIPES',len(fallback),'EXCLUDED',len(excluded))
    print('UNRESOLVED EVENTS',[(sid,r['name']) for sid,r in by_id.items() if sid not in groups])
    print('FALLBACK REASONS',Counter(r['reason'] for r in fallback))
    print('RTPC LAYERS',[(c['event_name'],sorted({n.get('source_node') for n in walk(c['graph']) if n.get('rtpc_layer')})) for c in cues if any(n.get('rtpc_layer') for n in walk(c['graph']))])

if __name__=='__main__':main()
