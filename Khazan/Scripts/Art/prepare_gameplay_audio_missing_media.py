from pathlib import Path
from collections import Counter
import json
import re
from prepare_gameplay_audio_scope import OUT,EXTRACT,read
index=read(EXTRACT/'Index03/AudioPackageIndex.json');by_name={}
for r in index:
    if r['path'].endswith('.wem'):by_name.setdefault(Path(r['path']).name,[]).append(r['path'])
needed={Path(r['media']).name for r in read(OUT/'NativeDecodedManifest01.json') if r['status']!='decoded'}
for p in (OUT/'BankRecipes09/txtp').glob('*.txtp'):
    needed.update(re.findall(r'Media/([\d]+\.wem)',p.read_text(encoding='utf-8-sig').split('# AUTOGENERATED')[0]))
requests=[];missing=[]
for name in needed:
    found=by_name.get(name,[])
    if len(found)==1:requests+=found
    else:missing.append({'media':name,'candidates':found})
(EXTRACT/'MissingMediaRequests.json').write_text(json.dumps(sorted(set(requests)),indent=2),encoding='utf-8')
(OUT/'MissingMediaPlan.json').write_text(json.dumps({'requests':requests,'missing':missing},indent=2),encoding='utf-8')
print('MEDIA CLOSURE',len(set(requests)),len(missing),'FAILED SAMPLE',[(r['media'],r.get('error','')[-150:]) for r in read(OUT/'NativeDecodedManifest01.json') if r['status']!='decoded'][:3])
facts=read(OUT/'BankNodeFacts.json')
for sid in ('857367060','2785835910','23130734','213595565'):
    f=facts.get(sid,{})
    print('BUS/NODE',sid,f.get('type'),[(r['name'],r.get('hashname') or r.get('valuefmt') or r['value']) for r in f.get('fields',[]) if r['type'] in ('tid','sid') or r['name'] in ('ulPluginID','sourceID','uNumChildren')][:30])
