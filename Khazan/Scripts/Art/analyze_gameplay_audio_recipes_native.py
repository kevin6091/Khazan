from collections import Counter
from pathlib import Path
import re
import json
from prepare_gameplay_audio_scope import OUT, read

groups=Counter();flags=Counter();others=Counter();langs=Counter()
for p in (OUT/'BankRecipes08/txtp').glob('*.txtp'):
    body=p.read_text(encoding='utf-8-sig').split('# AUTOGENERATED')[0]
    for line in body.splitlines():
        line=line.strip()
        if not line or line.startswith('#'):continue
        if line.startswith('group'):
            groups[re.sub(r'\d+', 'N', line)]+=1
        elif '.wem ' in line or line.endswith('.wem'):
            flags.update(re.findall(r'(#\w+)',line))
        else:others[line]+=1
print('GROUPS',groups.most_common(25))
print('FLAGS',flags)
print('OTHERS',others.most_common(22))
p=next((p for p in (OUT/'BankRecipes08/txtp').glob('*VO_Dmg*') if 'vo_kz_switch=kz]' in p.name))
print('KOREAN VO BODY',p.name,'\n'.join(p.read_text(encoding='utf-8-sig').splitlines()[:4]))
