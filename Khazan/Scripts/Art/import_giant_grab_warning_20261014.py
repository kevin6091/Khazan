def row(name):
    return next(r for r in ROWS if r["name"] == name and r["source_package"].startswith("BBQ/Content/_Kazan_/Art/VFX/"))


def source_tag(asset, info, boundary):
    lib = u.EditorAssetLibrary
    lib.set_metadata_tag(asset, "KZFXSourcePackage", info["source_package"])
    lib.set_metadata_tag(asset, "KZFXSourceSHA256", info["source_sha256"])
    lib.set_metadata_tag(asset, "KZFXRecoveryBoundary", boundary)
    save(asset)
    REPORT["assets"].append({"source": info["source_package"], "destination": info["destination"],
                             "native_class": asset.get_class().get_name(), "boundary": boundary})


def import_file(info, key, factory):
    old = u.load_asset(info["destination"])
    if old:
        assert u.EditorAssetLibrary.get_metadata_tag(old, "KZFXSourcePackage") == info["source_package"]
        return old
    task = u.AssetImportTask()
    for field, value in (("filename", str(ROOT / info[key])),
                         ("destination_path", info["destination"].rsplit("/", 1)[0]),
                         ("destination_name", info["name"]), ("automated", True),
                         ("replace_existing", False), ("save", False), ("factory", factory)):
        task.set_editor_property(field, value)
    TOOLS.import_asset_tasks([task])
    asset = u.load_asset(info["destination"])
    assert asset, info
    return asset


def textures():
    for info in (r for r in ROWS if r["source_type"] == "Texture2D"):
        texture = import_file(info, "source_image", u.TextureFactory())
        props = source(info).get("Properties", {})
        texture.set_editor_property("srgb", props.get("SRGB", False))
        texture.set_editor_property("lod_group", u.TextureGroup.TEXTUREGROUP_EFFECTS)
        source_tag(texture, info, "Original FModel PNG pixels; original UE texture compression/mips regenerated by this editor")


def expr(material, cls, idx):
    return LIB.create_material_expression(material, cls, -750 + idx % 4 * 220, idx // 4 * 160)


def link(a, output, b, pin):
    assert LIB.connect_material_expressions(a, output, b, pin), (a, output, b, pin)


def material(info, image, masked, atlas=False):
    asset = make(info, u.Material, u.MaterialFactoryNew())
    asset.modify()
    LIB.delete_all_material_expressions(asset)
    asset.set_editor_property("material_domain", u.MaterialDomain.MD_SURFACE)
    asset.set_editor_property("shading_model", u.MaterialShadingModel.MSM_UNLIT)
    asset.set_editor_property("blend_mode", u.BlendMode.BLEND_MASKED if masked else u.BlendMode.BLEND_TRANSLUCENT)
    asset.set_editor_property("two_sided", True)
    LIB.set_material_usage(asset, u.MaterialUsage.MATUSAGE_PARTICLE_SPRITES)
    LIB.set_material_usage(asset, u.MaterialUsage.MATUSAGE_MESH_PARTICLES)
    tex = expr(asset, u.MaterialExpressionTextureSample, 0)
    tex.set_editor_property("texture", u.load_asset(row(image)["destination"]))
    tex.set_editor_property("sampler_type", u.MaterialSamplerType.SAMPLERTYPE_LINEAR_COLOR)
    if atlas:
        # FT_Splash_Decal_02 has a 2x2 source atlas; its original cooked function
        # was stripped. Use the first source cell rather than showing all four.
        uv = expr(asset, u.MaterialExpressionTextureCoordinate, 1)
        half = expr(asset, u.MaterialExpressionConstant, 2)
        half.set_editor_property("r", 0.5)
        scaled = expr(asset, u.MaterialExpressionMultiply, 3)
        link(uv, "", scaled, "A")
        link(half, "", scaled, "B")
        link(scaled, "", tex, "UVs")
    color = expr(asset, u.MaterialExpressionParticleColor, 4)
    rgb = expr(asset, u.MaterialExpressionMultiply, 5)
    link(tex, "RGB" if atlas else "R", rgb, "A")
    link(color, "RGB", rgb, "B")
    assert LIB.connect_material_property(rgb, "", u.MaterialProperty.MP_EMISSIVE_COLOR)
    opacity = expr(asset, u.MaterialExpressionMultiply, 6)
    link(tex, "R", opacity, "A")
    link(color, "A", opacity, "B")
    assert LIB.connect_material_property(opacity, "", u.MaterialProperty.MP_OPACITY_MASK if masked else u.MaterialProperty.MP_OPACITY)
    LIB.recompile_material(asset)
    boundary = ("Source mask/color/particle alpha retained; cooked shader graph unavailable. "
                + ("2x2 atlas cell selection is a project adapter." if atlas else "Sharp/blur source pixels retained."))
    source_tag(asset, info, boundary)


def meshes():
    stage = OUT / "Staging"
    stage.mkdir(exist_ok=True)
    for info in (r for r in ROWS if r["source_type"] == "StaticMesh"):
        raw = bytearray((ROOT / info["source_mesh"]).read_bytes())
        offset = 0
        while offset < len(raw):
            chunk, _, size, count = struct.unpack_from("<20siii", raw, offset)
            offset += 32
            if chunk.rstrip(b"\0") == b"MATT0000":
                for i in range(count):
                    start = offset + i * size
                    token = ("KZGrabTemporary_" + str(i)).encode("ascii")
                    raw[start:start + 64] = token.ljust(64, b"\0")
            offset += size * count
        staged = stage / (info["name"] + ".pskx")
        staged.write_bytes(raw)
        info["staged_mesh"] = str(staged.relative_to(ROOT))
        asset = import_file(info, "staged_mesh", u.PSKXFactory())
        assert isinstance(asset, u.StaticMesh), info["destination"]
        source_tag(asset, info, "Original FModel PSKX geometry/UV; temporary importer material tokens, Cascade overrides material")


